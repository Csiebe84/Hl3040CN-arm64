"""Pin the native Fine-mode encoders to the Python reference.

`_fine_fast` is a C rewrite of two pure-Python byte loops, and a rewrite like
that fails quietly: the output stays a plausible XL2HB stream, so only a byte
comparison catches a divergence.  These tests replay a frozen corpus
(`tools/fine_golden.json`, regenerated by `tools/make_fine_golden.py`) that was
captured from the Python implementation before the extension existed.

The corpus holds 26256 scanlines taken from real printer captures plus 614
edge cases (empty input, single bytes, long runs, strides 1/2/3, random data),
each with the expected Stage-1 and Stage-2 output.

When the extension is absent the tests still run and compare Python against the
frozen corpus, so they pass on a machine without a compiler - they simply stop
covering the native path.
"""

from __future__ import annotations

import json
import unittest
from pathlib import Path

import fine_encoder
from fine_encoder import (
    HAS_CYTHON_FINE,
    compress_pattern_encode,
    compress_pattern_encode_py,
    compress_rle_preencode,
    compress_rle_preencode_py,
)

GOLDEN = Path(__file__).resolve().parent / "fine_golden.json.gz"


class GoldenCorpusTest(unittest.TestCase):
    """Both stages must reproduce the frozen corpus byte for byte."""

    @classmethod
    def setUpClass(cls) -> None:
        if not GOLDEN.exists():
            raise AssertionError(
                f"equivalence corpus missing: {GOLDEN}. The native encoders are then "
                f"unverified - regenerate with tools/make_fine_golden.py."
            )
        import gzip

        with gzip.open(GOLDEN, "rt") as handle:
            cls.corpus = json.load(handle)

    def _entries(self):
        # The corpus carries a single "cases" list; older revisions split it
        # into "cases" and "edges", so read both when present.
        for group in ("cases", "edges"):
            for tag, stage1_in, stage1_out, stage2_out in self.corpus.get(group, []):
                yield tag, bytes.fromhex(stage1_in), bytes.fromhex(stage1_out), bytes.fromhex(stage2_out)

    def test_stage1_matches_reference(self) -> None:
        bad = []
        for tag, stage1_in, stage1_out, _ in self._entries():
            if compress_rle_preencode(stage1_in) != stage1_out:
                bad.append(tag)
        self.assertEqual(bad[:5], [], f"{len(bad)} scanlines diverge in Stage 1")

    def test_stage2_matches_reference(self) -> None:
        bad = []
        for tag, _, stage1_out, stage2_out in self._entries():
            if compress_pattern_encode(stage1_out) != stage2_out:
                bad.append(tag)
        self.assertEqual(bad[:5], [], f"{len(bad)} scanlines diverge in Stage 2")

    def test_python_fallback_matches_reference(self) -> None:
        """The fallback must stay correct too - it is the only path without a compiler."""
        bad = []
        for tag, stage1_in, stage1_out, stage2_out in self._entries():
            if compress_rle_preencode_py(stage1_in) != stage1_out:
                bad.append(f"{tag}:stage1")
            elif compress_pattern_encode_py(stage1_out) != stage2_out:
                bad.append(f"{tag}:stage2")
        self.assertEqual(bad[:5], [], f"{len(bad)} divergences in the Python fallback")


class NativeAgreementTest(unittest.TestCase):
    """The native and Python paths must agree on input the corpus never saw."""

    def _agree(self, data: bytes) -> None:
        s1_native = compress_rle_preencode(data)
        s1_py = compress_rle_preencode_py(data)
        self.assertEqual(s1_native, s1_py, f"Stage 1 diverges on {data[:16].hex()}...")
        self.assertEqual(
            compress_pattern_encode(s1_py),
            compress_pattern_encode_py(s1_py),
            f"Stage 2 diverges on {data[:16].hex()}...",
        )

    def test_structured_patterns(self) -> None:
        import random

        rnd = random.Random(20261030)
        cases = [
            b"",
            b"\x00",
            b"\xff",
            b"\x00" * 4096,
            b"\xff" * 4096,
            bytes(range(256)) * 4,
            b"\x12\x34\x56" * 300,
        ]
        for _ in range(300):
            n = rnd.randrange(0, 600)
            cases.append(bytes(rnd.randrange(256) for _ in range(n)))
        for _ in range(300):
            # Runs and strides are what the Stage-2 window logic keys on.
            period = rnd.randrange(1, 5)
            pattern = bytes(rnd.randrange(256) for _ in range(period))
            n = rnd.randrange(1, 400)
            cases.append((pattern * (n // period + 1))[:n])

        for data in cases:
            self._agree(data)

    def test_gil_released_path_is_exercised(self) -> None:
        """A long input must complete without the GIL; a sizeable buffer is required."""
        self._agree(bytes(200000))


class EncoderWiringTest(unittest.TestCase):
    def test_encode_fine_plane_uses_the_active_implementation(self) -> None:
        line = bytes([0x11, 0x22, 0x00, 0xFF] * 40)
        expected = compress_pattern_encode(compress_rle_preencode(line))
        self.assertEqual(fine_encoder.encode_fine_plane(line), expected)

    def test_blank_line_is_empty(self) -> None:
        self.assertEqual(fine_encoder.encode_fine_plane(bytes(512)), b"")

    def test_reports_which_implementation_is_active(self) -> None:
        # Informational: tells a reader of the test log whether the native
        # extension was actually loaded for this run.
        print(f"\nHAS_CYTHON_FINE={HAS_CYTHON_FINE}")


if __name__ == "__main__":
    unittest.main()
